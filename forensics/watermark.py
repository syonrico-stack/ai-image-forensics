"""模块：角标水印检测（AI 生成内容的显式标识）

背景：中国《人工智能生成合成内容标识办法》要求 AI 生成内容带显式标识，
国产工具（豆包、即梦、Kimi 等）通常以角标文字形式呈现，如"豆包AI生成"。
本模块裁剪四角区域，放大 + 预处理后 OCR，匹配 AI 标识关键词。

依赖：tesseract（容器内已装 chi_sim 中文包；裸 Python 运行需自行安装，
缺失时本模块自动跳过，不影响其他模块）。
"""
import shutil

import cv2
import numpy as np

from .common import finding, module_result, resize_for_analysis

# 命中即视为 AI 显式标识的关键词（小写比较）
AI_KEYWORDS = [
    "ai生成", "ai 生成", "aigc", "ai制作", "ai 制作", "人工智能生成",
    "豆包", "即梦", "可灵", "混元", "通义万相", "文心一格", "kimi",
    "doubao", "jimeng", "midjourney", "dall-e", "dalle", "firefly",
    "stable diffusion", "ideogram", "recraft", "nano banana",
    "ai-generated", "generated by ai", "generated with ai",
]
# 四角裁剪比例（左下/右下优先——国产工具角标绝大多数在底部两角）
CORNERS = [(0.0, 0.85, 0.40, 1.0), (0.60, 0.85, 1.0, 1.0),
           (0.0, 0.0, 0.40, 0.15), (0.60, 0.0, 1.0, 0.15)]
OCR_TIMEOUT = 8          # 单角 OCR 超时（秒）
MAX_CORNER_PX = 420_000  # 裁剪区域放大后的像素上限


def _ocr_corner(img_bgr, box):
    h, w = img_bgr.shape[:2]
    x0, y0, x1, y1 = box
    crop = img_bgr[int(h * y0):int(h * y1), int(w * x0):int(w * x1)]
    if crop.size == 0:
        return ""
    # 放大提升小字识别率，但限制总像素控制耗时
    scale = min(3.0, (MAX_CORNER_PX / crop.size) ** 0.5)
    if scale > 1.0:
        crop = cv2.resize(crop, None, fx=scale, fy=scale, interpolation=cv2.INTER_CUBIC)
    gray = cv2.cvtColor(crop, cv2.COLOR_BGR2GRAY)
    gray = cv2.createCLAHE(3.0, (8, 8)).apply(gray)
    try:
        data = pytesseract.image_to_data(
            gray, config="--psm 6", timeout=OCR_TIMEOUT,
            output_type=pytesseract.Output.DICT)
    except Exception:
        return ""
    # 只保留置信度足够高的词，过滤纹理误读产生的乱码
    words = [t for t, c in zip(data["text"], data["conf"])
             if str(c) not in ("-1",) and float(c) >= 45 and t.strip()]
    return " ".join(words).strip()


def analyze(path, pil, arr, config=None):
    global pytesseract
    if shutil.which("tesseract") is None:
        return module_result("watermark", status="skipped",
                             note="未检测到 tesseract OCR（Docker 部署默认已含；裸 Python 运行需 brew/apt 安装 tesseract）",
                             findings=[finding("info", "WM_SKIPPED", "OCR 环境不可用，跳过角标检测")])
    try:
        import pytesseract as _pt
        pytesseract = _pt
        langs = set(pytesseract.get_languages())
    except Exception as e:
        return module_result("watermark", status="skipped",
                             note=f"pytesseract 不可用：{e}",
                             findings=[finding("info", "WM_SKIPPED", "OCR 组件不可用")])
    if "chi_sim" not in langs:
        lang_note = "（注意：当前仅有英文 OCR 包，中文角标识别能力受限；Docker 部署含中文包）"
    else:
        lang_note = ""

    small, _ = resize_for_analysis(arr, 1200)
    bgr = cv2.cvtColor(small, cv2.COLOR_RGB2BGR)
    all_text, hits = [], []
    for box in CORNERS:
        txt = _ocr_corner(bgr, box)
        if txt:
            all_text.append(txt)
            low = txt.lower().replace(" ", "")
            for kw in AI_KEYWORDS:
                if kw.replace(" ", "") in low:
                    hits.append(kw)
        if hits:
            break  # 命中即提前退出，节省时间

    if hits:
        return module_result("watermark", findings=[finding(
            "high", "WATERMARK_AI_LABEL",
            f"图片角部检测到 AI 生成显式标识（命中关键词：{'、'.join(sorted(set(hits)))}），"
            f"OCR 原文：{' | '.join(all_text)[:150]}",
            {"keywords": sorted(set(hits)), "ocr_text": all_text})],
            metrics={"ocr_text": all_text})
    # 未命中时 OCR 原文只进 metrics（供调试），不作为发现项——纹理误读的乱码不构成信息
    return module_result("watermark", findings=[
        finding("info", "WATERMARK_NONE", f"四角未检出 AI 标识文字{lang_note}")],
        metrics={"ocr_text": all_text})
